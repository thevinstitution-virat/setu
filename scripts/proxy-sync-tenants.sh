#!/bin/sh
# Keeps Traefik routes (and so Let's Encrypt certificates) for every business
# address in step with the database: <slug>.<PLATFORM_DOMAIN> for each business
# that isn't closed, plus every verified custom domain.
#
# Why: Coolify 4.x can't route a wildcard (*.domain) to an app, and a wildcard
# certificate needs a DNS-provider token. One router per address lets Traefik
# get each certificate with the ordinary HTTP check instead.
#
# Runs on the Docker host as root, every few seconds (see docs/DEPLOY.md).
# Writes a Traefik file-provider config only when the address list changes.
#
# Settings (environment):
#   SETU_DB_CONTAINER  Postgres container name (Coolify database uuid)
#   SETU_DB_USER       superuser inside that container (default setu_admin)
#   SETU_DB_NAME       database (default setu)
#   PLATFORM_DOMAIN    e.g. ss.vpd.ceo
#   SETU_SERVICE       Traefik service of the web app, e.g.
#                      https-0-<app uuid>-web-<hash>@docker (Coolify's label for domain 0)
#   SETU_OUT           output file (default /data/coolify/proxy/dynamic/setu-tenants.yaml)
#   SETU_RESOLVER      ACME resolver (default letsencrypt)
set -eu

: "${SETU_DB_CONTAINER:?}" "${PLATFORM_DOMAIN:?}" "${SETU_SERVICE:?}"
DB_USER=${SETU_DB_USER:-setu_admin}
DB_NAME=${SETU_DB_NAME:-setu}
OUT=${SETU_OUT:-/data/coolify/proxy/dynamic/setu-tenants.yaml}
RESOLVER=${SETU_RESOLVER:-letsencrypt}

tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.hosts"' EXIT

# A failed query must never empty the routes, so stop here on any error.
docker exec "$SETU_DB_CONTAINER" psql -U "$DB_USER" -d "$DB_NAME" -AtX -v ON_ERROR_STOP=1 -c "
  select lower(slug) || '.' || '$PLATFORM_DOMAIN' from \"Tenant\" where status <> 'CLOSED'
  union
  select lower(\"verifiedHost\") from \"TenantDomain\" where \"verifiedHost\" is not null" >"$tmp"

# Only plain host names get through (nothing that could break the YAML or the rule).
grep -E '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$' "$tmp" | sort -u >"$tmp.hosts" || true

{
  echo "# Generated by scripts/proxy-sync-tenants.sh. Do not edit: it is rewritten from the database."
  echo "http:"
  echo "  middlewares:"
  echo "    setu-tenant-https:"
  echo "      redirectScheme:"
  echo "        scheme: https"
  echo "        permanent: true"
  if [ -s "$tmp.hosts" ]; then
    echo "  routers:"
    while read -r h; do
      n=$(echo "$h" | tr '.' '-')
      echo "    setu-$n-http:"
      echo "      entryPoints: [http]"
      echo "      rule: \"Host(\`$h\`)\""
      echo "      middlewares: [setu-tenant-https]"
      echo "      service: $SETU_SERVICE"
      echo "    setu-$n:"
      echo "      entryPoints: [https]"
      echo "      rule: \"Host(\`$h\`)\""
      echo "      service: $SETU_SERVICE"
      echo "      tls:"
      echo "        certResolver: $RESOLVER"
    done <"$tmp.hosts"
  fi
} >"$tmp"

if [ -f "$OUT" ] && cmp -s "$tmp" "$OUT"; then
  exit 0
fi
# Same directory + rename, so Traefik never reads a half-written file.
# (Traefik only loads .yml/.yaml/.toml, so the .part name is ignored.)
cp "$tmp" "$OUT.part"
chmod 644 "$OUT.part"
mv -f "$OUT.part" "$OUT"
echo "$(date -u +%FT%TZ) routes: $(wc -l <"$tmp.hosts") address(es)"
